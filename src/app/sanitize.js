/* ============================================================
   外から入ってくるデータの確かめと、画面に出すときのエスケープ
   ============================================================ */
/* 画面（innerHTML）に文字を入れるときは必ず通す。属性の値にも使える */
function esc(v){
  return String(v === undefined || v === null ? "" : v)
    .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;").replace(/'/g, "&#39;");
}
